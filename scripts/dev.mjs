// `wrangler dev` rewrites every request's Host to the first configured route, which breaks
// subdomain routing locally. Generate a route-less copy of wrangler.toml and run dev against it.
import { spawn } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

if (!existsSync('wrangler.toml')) {
  console.error('wrangler.toml not found: cp wrangler.toml.example wrangler.toml and edit it first.');
  process.exit(1);
}
const src = readFileSync('wrangler.toml', 'utf8');
// Remove every route form wrangler accepts: `routes = [ ... ]` (one or several lines), `route = ...`, and
// `[[routes]]` tables. No routes: nothing to remove.
const out = src
  .replace(/^routes\s*=\s*\[[^\]]*\][^\n]*$/m, '# routes removed for local dev')
  .replace(/^route\s*=.*$/m, '# route removed for local dev')
  .replace(/^\[\[routes\]\][^\[]*/gm, '# [[routes]] removed for local dev\n');
if (/^\s*(routes?\s*=|\[\[routes\]\])/m.test(out)) {
  console.warn('warning: a route is still configured in wrangler.dev.toml; subdomain routing may not work locally');
}
writeFileSync('wrangler.dev.toml', `# GENERATED by scripts/dev.mjs — do not edit\n${out}`);

const child = spawn('npx', ['wrangler', 'dev', '-c', 'wrangler.dev.toml', ...process.argv.slice(2)], { stdio: 'inherit' });
child.on('exit', (code) => process.exit(code ?? 0));
